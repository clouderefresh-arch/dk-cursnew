def fmt(n, d=2):
    s = f"{n:,.{d}f}"
    return s.replace(",", " ").replace(".", ",")


def fmt_coord(n):
    return f"{n:.2f}".replace(".", ",")


def dist(a, b):
    return math.hypot(b[1] - a[1], b[2] - a[2])


def azimuth(a, b):
    return math.degrees(math.atan2(b[2] - a[2], b[1] - a[1])) % 360


def dms(ang):
    ang = ang % 360
    d = int(ang)
    m_f = (ang - d) * 60
    m = int(m_f)
    s = (m_f - m) * 60
    if s >= 59.995:
        s = 0
        m += 1
    if m == 60:
        m = 0
        d += 1
    return f"{d}°{m:02d}'{s:04.1f}\"".replace(".", ",")


def interior_angle(prev, cur, nxt):
    a_back = azimuth(cur, prev)
    a_fwd = azimuth(cur, nxt)
    turn = (a_fwd - a_back) % 360
    return (360 - turn) % 360


def shoelace():
    s = 0.0
    rows = []
    for i in range(5):
        j = (i + 1) % 5
        prod = PTS[i][1] * PTS[j][2] - PTS[j][1] * PTS[i][2]
        s += prod
        rows.append((PTS[i][0], PTS[j][0], prod))
    return abs(s) / 2, rows


def set_run_font(run, size=14, bold=False, italic=False):
    run.font.name = "Times New Roman"
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    run.font.color.rgb = RGBColor(0, 0, 0)
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:ascii"), "Times New Roman")
    rFonts.set(qn("w:hAnsi"), "Times New Roman")
    rFonts.set(qn("w:cs"), "Times New Roman")
    rFonts.set(qn("w:eastAsia"), "Times New Roman")


def set_paragraph_format(p, *, align="justify", first=1.25, before=0, after=0, line=1.5, left=0):
    pf = p.paragraph_format
    pf.line_spacing = line
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.first_line_indent = Cm(first) if first else Cm(0)
    pf.left_indent = Cm(left)
    align_map = {
        "justify": WD_ALIGN_PARAGRAPH.JUSTIFY,
        "center": WD_ALIGN_PARAGRAPH.CENTER,
        "left": WD_ALIGN_PARAGRAPH.LEFT,
        "right": WD_ALIGN_PARAGRAPH.RIGHT,
    }
    p.alignment = align_map[align]


def add_page_number(paragraph):
    run = paragraph.add_run()
    set_run_font(run, 14)
    fld_begin = OxmlElement("w:fldChar")
    fld_begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    fld_end = OxmlElement("w:fldChar")
    fld_end.set(qn("w:fldCharType"), "end")
    run._r.append(fld_begin)
    run._r.append(instr)
    run._r.append(fld_end)


def shade_cell(cell, color):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), color)
    shd.set(qn("w:val"), "clear")
    tcPr.append(shd)


def set_cell_border(cell):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcBorders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), "000000")
        tcBorders.append(el)
    tcPr.append(tcBorders)


def prevent_row_split(row):
    tr = row._tr
    trPr = tr.get_or_add_trPr()
    cant = OxmlElement("w:cantSplit")
    trPr.append(cant)


class Work:
    def __init__(self, pages):
        self.pages = pages
        self.doc = Document()
        self._setup()

    def _setup(self):
        section = self.doc.sections[0]
        section.page_width = Mm(210)
        section.page_height = Mm(297)
        section.left_margin = Mm(30)
        section.right_margin = Mm(10)
        section.top_margin = Mm(20)
        section.bottom_margin = Mm(20)
        section.header_distance = Mm(10)
        section.footer_distance = Mm(10)
        header = section.header
        header.is_linked_to_previous = False
        hp = header.paragraphs[0]
        hp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        hp.paragraph_format.space_before = Pt(0)
        hp.paragraph_format.space_after = Pt(0)
        add_page_number(hp)
        style = self.doc.styles["Normal"]
        style.font.name = "Times New Roman"
        style.font.size = Pt(14)
        style.paragraph_format.line_spacing = 1.5
        rPr = style.element.get_or_add_rPr()
        rFonts = rPr.find(qn("w:rFonts"))
        if rFonts is None:
            rFonts = OxmlElement("w:rFonts")
            rPr.append(rFonts)
        rFonts.set(qn("w:ascii"), "Times New Roman")
        rFonts.set(qn("w:hAnsi"), "Times New Roman")
        rFonts.set(qn("w:cs"), "Times New Roman")
        rFonts.set(qn("w:eastAsia"), "Times New Roman")

    def p(self, text, **kw):
        par = self.doc.add_paragraph()
        size = kw.pop("size", 14)
        bold = kw.pop("bold", False)
        italic = kw.pop("italic", False)
        set_paragraph_format(par, **kw)
        run = par.add_run(text)
        set_run_font(run, size, bold, italic)
        return par

    def rich(self, parts, **kw):
        """parts: list of (text, bold, italic, size)."""
        par = self.doc.add_paragraph()
        set_paragraph_format(par, **{k: v for k, v in kw.items() if k in ("align", "first", "before", "after", "line", "left")})
        for text, bold, italic, size in parts:
            run = par.add_run(text)
            set_run_font(run, size, bold, italic)
        return par

    def h1(self, text):
        self.doc.add_page_break()
        return self.p(text, align="center", first=0, before=0, after=12, bold=True)

    def h2(self, text):
        return self.p(text, align="center", first=0, before=12, after=12, bold=True)

    def caption(self, text):
        return self.p(text, align="left", first=0, before=6, after=4, size=14)

    def fig_caption(self, text):
        return self.p(text, align="center", first=0, before=4, after=8)

    def formula(self, text, number):
        par = self.doc.add_paragraph()
        set_paragraph_format(par, align="center", first=0, before=6, after=6)
        run = par.add_run(f"{text}    {number}")
        set_run_font(run, 14)
        return par

    def image(self, path, width_cm):
        par = self.doc.add_paragraph()
        set_paragraph_format(par, align="center", first=0, before=6, after=2)
        par.paragraph_format.keep_together = True
        par.paragraph_format.keep_with_next = True
        run = par.add_run()
        run.add_picture(str(path), width=Cm(width_cm))
        return par

    def table(self, headers, rows, widths):
        tbl = self.doc.add_table(rows=1 + len(rows), cols=len(headers))
        tbl.alignment = WD_TABLE_ALIGNMENT_CENTER if False else 1
        tbl.autofit = False
        tbl.allow_autofit = False
        total = sum(widths)
        tblPr = tbl._tbl.tblPr
        tblW = tblPr.find(qn("w:tblW"))
        if tblW is None:
            tblW = OxmlElement("w:tblW")
            tblPr.append(tblW)
        tblW.set(qn("w:w"), str(int(total * 567)))
        tblW.set(qn("w:type"), "dxa")
        # center table
        jc = tblPr.find(qn("w:jc"))
        if jc is None:
            jc = OxmlElement("w:jc")
            tblPr.append(jc)
        jc.set(qn("w:val"), "center")
        grid = tbl._tbl.find(qn("w:tblGrid"))
        if grid is not None:
            for child in list(grid):
                grid.remove(child)
        else:
            grid = OxmlElement("w:tblGrid")
            tbl._tbl.insert(1, grid)
        for w in widths:
            gc = OxmlElement("w:gridCol")
            gc.set(qn("w:w"), str(int(w * 567)))
            grid.append(gc)

        def fill(cell, text, header=False):
            cell.text = ""
            cell.vertical_alignment = 1
            p = cell.paragraphs[0]
            set_paragraph_format(p, align="center", first=0, before=0, after=0, line=1.0)
            run = p.add_run(text)
            set_run_font(run, 12, bold=header)
            set_cell_border(cell)
            tc = cell._tc
            tcPr = tc.get_or_add_tcPr()
            tcW = tcPr.find(qn("w:tcW"))
            if tcW is None:
                tcW = OxmlElement("w:tcW")
                tcPr.append(tcW)
            # width set later per column
            if header:
                shade_cell(cell, "E8E8E8")

        for j, h in enumerate(headers):
            fill(tbl.rows[0].cells[j], h, True)
        prevent_row_split(tbl.rows[0])
        tr = tbl.rows[0]._tr
        trPr = tr.get_or_add_trPr()
        th = OxmlElement("w:tblHeader")
        trPr.append(th)
        for i, row in enumerate(rows):
            prevent_row_split(tbl.rows[i + 1])
            for j, val in enumerate(row):
                fill(tbl.rows[i + 1].cells[j], str(val), False)
        for row in tbl.rows:
            for j, cell in enumerate(row.cells):
                tc = cell._tc
                tcPr = tc.get_or_add_tcPr()
                tcW = tcPr.find(qn("w:tcW"))
                if tcW is None:
                    tcW = OxmlElement("w:tcW")
                    tcPr.append(tcW)
                tcW.set(qn("w:w"), str(int(widths[j] * 567)))
                tcW.set(qn("w:type"), "dxa")
        return tbl

    def toc_line(self, title, key, level=0):
        par = self.doc.add_paragraph()
        set_paragraph_format(par, align="left", first=0, before=0, after=0, line=1.0, left=0 if level == 0 else 1.25)
        par.paragraph_format.tab_stops.add_tab_stop(Cm(17.0), WD_TAB_ALIGNMENT.RIGHT, WD_TAB_LEADER.DOTS)
        page = self.pages.get(key, "")
        run = par.add_run(title + "\t" + str(page))
        set_run_font(run, 14, bold=(level == 0))
        return par

    def save(self, path):
        self.doc.save(path)


